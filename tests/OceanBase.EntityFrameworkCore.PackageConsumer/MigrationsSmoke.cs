using System;
using System.Linq;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using OceanBase.EntityFrameworkCore;

namespace PackageConsumer
{
    internal static class MigrationsSmoke
    {
        internal const string Id = "20261113090000_PackageInitial";

        public static void Run(OceanBaseCompatibilityMode mode)
        {
            using var context = new MigrationContext(new DbContextOptionsBuilder<MigrationContext>()
                .UseOceanBase("Server=localhost;Database=package_smoke", mode)
                .EnableOceanBaseSchemaManagement("package_smoke").Options);
            var model = context.GetService<IDesignTimeModel>().Model;
            var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
            var commands = context.GetService<IMigrationsSqlGenerator>().Generate(operations, model);
            var identity = mode == OceanBaseCompatibilityMode.MySql ? "AUTO_INCREMENT" : "GENERATED BY DEFAULT AS IDENTITY";
            if (!commands.Any(c => c.CommandText.Contains(identity, StringComparison.Ordinal))
                || commands.Any(c => !c.TransactionSuppressed))
                throw new Exception("Packed model differences lost identity or implicit-DDL-commit semantics.");
            if (!context.Database.GetMigrations().SequenceEqual(new[] { Id }))
                throw new Exception("Packed migration assembly discovery failed.");
            var migrator = context.GetService<IMigrator>();
            var forward = migrator.GenerateScript();
            var reverse = migrator.GenerateScript(Id, Migration.InitialDatabase);
            var idempotent = migrator.GenerateScript(options: MigrationsSqlGenerationOptions.Idempotent);
            if (!forward.Contains("CREATE TABLE", StringComparison.Ordinal) || !forward.Contains(Id, StringComparison.Ordinal)
                || forward.Contains("START TRANSACTION", StringComparison.Ordinal)
                || !reverse.Contains("DROP TABLE", StringComparison.Ordinal) || !reverse.Contains("DELETE FROM", StringComparison.Ordinal)
                || !idempotent.Contains(mode == OceanBaseCompatibilityMode.MySql ? "PREPARE" : "IF ob_count = 0 THEN", StringComparison.Ordinal))
                throw new Exception("Packed migration scripts lost upgrade, downgrade or history guards.");
            Console.WriteLine($"{mode}: packed model differences, migration discovery and forward/reverse/idempotent scripts passed (offline).");
        }

        public sealed class MigrationContext(DbContextOptions<MigrationContext> options) : DbContext(options)
        {
            protected override void OnModelCreating(ModelBuilder builder)
            {
                builder.Entity("PackageMigrationRow", row =>
                {
                    row.ToTable("MigrationRows");
                    row.Property<int>("Id").ValueGeneratedOnAdd();
                    row.HasKey("Id");
                });
            }
        }
    }

    [DbContext(typeof(MigrationsSmoke.MigrationContext))]
    [Migration(MigrationsSmoke.Id)]
    public sealed class PackageInitialMigration : Migration
    {
        protected override void Up(MigrationBuilder builder)
            => builder.CreateTable("MigrationRows", columns: table => new
            {
                Id = table.Column<int>(nullable: false).Annotation("OceanBase:Identity", true)
            }, constraints: table => table.PrimaryKey("PK_MigrationRows", row => row.Id));
        protected override void Down(MigrationBuilder builder) => builder.DropTable("MigrationRows");
    }
}
