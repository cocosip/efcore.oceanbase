using System;
using System.Collections.Generic;
using System.Data;
using System.Data.Common;
using System.Linq;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using OceanBase.EntityFrameworkCore;

namespace PackageConsumer;

internal static class ManyToManySmoke
{
    internal static void Run(OceanBaseCompatibilityMode mode)
    {
        foreach (var async in new[] { false, true }) RunAsync(mode, async).GetAwaiter().GetResult();
        Console.WriteLine($"{mode}: packed many-to-many schema, Include and tracked link changes passed (offline).");
    }

    private static async Task RunAsync(OceanBaseCompatibilityMode mode, bool async)
    {
        var commands = new Commands();
        await using var context = new LinkContext(new DbContextOptionsBuilder<LinkContext>()
            .UseOceanBase("Server=offline.invalid;Database=package_smoke", mode)
            .EnableServiceProviderCaching(false).AddInterceptors(new NoNetwork(), commands).Options);
        // Source tests verify automatic transactions; this package fixture intercepts commands before execution.
        context.Database.AutoTransactionBehavior = AutoTransactionBehavior.Never;
        var script = context.Database.GenerateCreateScript();
        if (Regex.Matches(script, "CREATE TABLE").Count != 3 || Regex.Matches(script, "FOREIGN KEY").Count != 2
            || Regex.Matches(script, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY").Count != 2)
            throw new Exception("Packed many-to-many schema lost join keys or generated an extra identity.");
        commands.ReadRows = true;
        var query = context.Set<Student>().Include(s => s.Courses).OrderBy(s => s.Id);
        var students = async ? await query.ToListAsync() : query.ToList();
        if (students.Count != 2 || students[0].Courses.Count != 1 || students[1].Courses.Count != 0
            || !ReferenceEquals(students[0], students[0].Courses[0].Students.Single())
            || !commands.Sql.Single().Contains("LEFT JOIN", StringComparison.Ordinal))
            throw new Exception("Packed many-to-many Include or inverse fixup failed.");
        context.ChangeTracker.Clear();
        commands.ReadRows = false;
        commands.Sql.Clear();
        var student = new Student { Name = "new" };
        var course = new Course { Name = "course" };
        student.Courses.Add(course);
        context.Add(student);
        if (await Save(context, async) != 3 || student.Id != 101 || course.Id != 101
            || !commands.Sql.Last().Contains("Memberships", StringComparison.Ordinal)
            || !commands.Inputs.Last().SequenceEqual(new object?[] { 101, 101 }))
            throw new Exception("Packed generated principal keys did not reach the join row.");
        commands.Sql.Clear();
        student.Courses.Remove(course);
        if (await Save(context, async) != 1 || commands.Sql.Count != 1
            || !commands.Sql[0].StartsWith("DELETE FROM", StringComparison.Ordinal)
            || !commands.Sql[0].Contains("Memberships", StringComparison.Ordinal)
            || course.Students.Count != 0 || context.ChangeTracker.Entries().Count() != 2)
            throw new Exception("Packed link removal changed a principal or lost inverse fixup.");
    }

    private static Task<int> Save(DbContext context, bool async)
        => async ? context.SaveChangesAsync() : Task.FromResult(context.SaveChanges());
    private sealed class LinkContext(DbContextOptions<LinkContext> options) : DbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder model)
        {
            model.Entity<Student>().ToTable("Students").Property(s => s.Name).HasMaxLength(40);
            model.Entity<Course>().ToTable("Courses").Property(c => c.Name).HasMaxLength(40);
            model.Entity<Student>().HasMany(s => s.Courses).WithMany(c => c.Students)
                .UsingEntity<Dictionary<string, object>>("Membership",
                    r => r.HasOne<Course>().WithMany().HasForeignKey("CourseId"),
                    l => l.HasOne<Student>().WithMany().HasForeignKey("StudentId"),
                    j => { j.ToTable("Memberships"); j.HasKey("CourseId", "StudentId"); });
        }
    }
    private sealed class Student { public int Id { get; set; } public string Name { get; set; } = ""; public List<Course> Courses { get; set; } = []; }
    private sealed class Course { public int Id { get; set; } public string Name { get; set; } = ""; public List<Student> Students { get; set; } = []; }
    private sealed class Commands : DbCommandInterceptor
    {
        internal bool ReadRows { get; set; }
        internal List<string> Sql { get; } = [];
        internal List<object?[]> Inputs { get; } = [];
        private void Capture(DbCommand command)
        {
            Sql.Add(command.CommandText);
            Inputs.Add(command.Parameters.Cast<DbParameter>().Where(p => p.Direction == ParameterDirection.Input).Select(p => p.Value).ToArray());
        }
        public override InterceptionResult<int> NonQueryExecuting(DbCommand command, CommandEventData data, InterceptionResult<int> result)
        {
            Capture(command);
            foreach (DbParameter parameter in command.Parameters)
                if (parameter.Direction == ParameterDirection.Output) parameter.Value = 101;
            return InterceptionResult<int>.SuppressWithResult(1);
        }
        public override ValueTask<InterceptionResult<int>> NonQueryExecutingAsync(DbCommand command, CommandEventData data,
            InterceptionResult<int> result, CancellationToken token = default) => ValueTask.FromResult(NonQueryExecuting(command, data, result));
        public override InterceptionResult<DbDataReader> ReaderExecuting(DbCommand command, CommandEventData data, InterceptionResult<DbDataReader> result)
        {
            Capture(command);
            var table = new DataTable();
            var types = ReadRows ? new[] { typeof(int), typeof(string), typeof(int), typeof(int), typeof(int), typeof(string) } : [typeof(int)];
            foreach (var type in types) table.Columns.Add("C" + table.Columns.Count, type);
            if (ReadRows)
            {
                if (!command.CommandText.Replace("`", "").Replace("\"", "").StartsWith(
                    "SELECT s.Id, s.Name, s0.CourseId, s0.StudentId, s0.Id, s0.Name", StringComparison.Ordinal))
                    throw new Exception("Packed many-to-many projection changed independently of fixture rows.");
                table.Rows.Add(1, "one", 10, 1, 10, "course");
                table.Rows.Add(2, "empty", DBNull.Value, DBNull.Value, DBNull.Value, DBNull.Value);
            }
            else table.Rows.Add(101);
            return InterceptionResult<DbDataReader>.SuppressWithResult(table.CreateDataReader());
        }
        public override ValueTask<InterceptionResult<DbDataReader>> ReaderExecutingAsync(DbCommand command, CommandEventData data,
            InterceptionResult<DbDataReader> result, CancellationToken token = default) => ValueTask.FromResult(ReaderExecuting(command, data, result));
    }
    private sealed class NoNetwork : DbConnectionInterceptor
    {
        public override InterceptionResult ConnectionOpening(DbConnection connection, ConnectionEventData data, InterceptionResult result)
            => InterceptionResult.Suppress();
        public override ValueTask<InterceptionResult> ConnectionOpeningAsync(DbConnection connection, ConnectionEventData data,
            InterceptionResult result, CancellationToken token = default) => ValueTask.FromResult(InterceptionResult.Suppress());
    }
}
