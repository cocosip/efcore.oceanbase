using System;
using System.Collections.Generic;
using System.Data;
using System.Data.Common;
using System.Linq;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using OceanBase.EntityFrameworkCore;
using OceanBaseDecimal = OceanBaseConnector.OceanBaseDecimal;

namespace PackageConsumer;

internal static class SplittingSmoke
{
    public static void Run(OceanBaseCompatibilityMode mode)
    {
        foreach (var async in new[] { false, true }) RunAsync(mode, async).GetAwaiter().GetResult();
        Console.WriteLine($"{mode}: packed entity/table splitting schema, queries and CRUD passed (offline).");
    }

    private static async Task RunAsync(OceanBaseCompatibilityMode mode, bool async)
    {
        var commands = new Commands();
        await using var context = new SplitContext(new DbContextOptionsBuilder<SplitContext>()
            .UseOceanBase("Server=offline.invalid;Database=package_smoke", mode)
            .EnableServiceProviderCaching(false).AddInterceptors(new NoNetwork(), commands).Options);
        // This package fixture intercepts commands; source tests verify default automatic transactions separately.
        context.Database.AutoTransactionBehavior = AutoTransactionBehavior.Never;
        var script = context.Database.GenerateCreateScript();
        var model = context.GetService<IDesignTimeModel>().Model;
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        var migrated = string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(operations, model).Select(c => c.CommandText));
        foreach (var sql in new[] { script, migrated })
            if (Regex.Matches(sql, "CREATE TABLE").Count != 3
                || Regex.Matches(sql, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY").Count != 2
                || Regex.Matches(sql, "FOREIGN KEY").Count != 1)
                throw new Exception("Packed splitting schema generated extra tables/identities or lost the fragment FK.");

        commands.Query = "split";
        var query = context.Set<Row>();
        var row = async ? await query.SingleAsync() : query.Single();
        if (row.Id != 101 || row.Name != "row" || row.Text is not null
            || !commands.Sql.Single().Contains("INNER JOIN", StringComparison.Ordinal))
            throw new Exception("Packed entity-split materialization failed.");
        context.ChangeTracker.Clear();
        commands.Query = "shared";
        var shared = context.Set<Owner>().Include(o => o.Detail).OrderBy(o => o.Id);
        var owners = async ? await shared.ToArrayAsync() : shared.ToArray();
        if (owners.Length != 2 || owners[0].Detail?.Text != "detail" || owners[1].Detail is not null
            || !ReferenceEquals(owners[0], owners[0].Detail!.Owner))
            throw new Exception("Packed optional shared-row materialization failed.");
        context.ChangeTracker.Clear();
        commands.Query = null;
        commands.Sql.Clear();
        var inserted = new Row { Name = "new", Text = "detail" };
        context.Add(inserted);
        if (await Save(context, async) != 2 || inserted.Id != 101 || !commands.Sql[0].Contains("SplitRows", StringComparison.Ordinal)
            || !commands.Inputs.Last().Contains(101))
            throw new Exception("Packed entity-split identity propagation failed.");
        commands.Sql.Clear();
        inserted.Text = null;
        if (await Save(context, async) != 1 || !commands.Sql.Single().Contains("SplitDetails", StringComparison.Ordinal))
            throw new Exception("Packed entity-split owning-table update failed.");
        commands.Sql.Clear();
        context.Remove(inserted);
        if (await Save(context, async) != 2 || !commands.Sql[0].Contains("SplitDetails", StringComparison.Ordinal)
            || !commands.Sql[1].Contains("SplitRows", StringComparison.Ordinal))
            throw new Exception("Packed entity-split deletion order failed.");

        commands.Sql.Clear();
        var owner = new Owner { Name = "new-owner", Detail = new Detail { Text = "new-detail" } };
        context.Add(owner);
        await Save(context, async);
        if (owner.Id != 101 || owner.Detail.Id != 101 || commands.Sql.Count(sql => sql.StartsWith("INSERT", StringComparison.Ordinal)) != 1)
            throw new Exception("Packed shared-row insert or shared identity failed.");
        commands.Sql.Clear();
        owner.Name = "changed-owner";
        owner.Detail.Text = "changed-detail";
        await Save(context, async);
        if (commands.Sql.Count != 1 || !commands.Inputs.Last().Contains("changed-owner") || !commands.Inputs.Last().Contains("changed-detail"))
            throw new Exception("Packed shared-row merged update failed.");
        commands.Sql.Clear();
        context.Remove(owner);
        await Save(context, async);
        if (commands.Sql.Count != 1 || !commands.Sql[0].StartsWith("DELETE", StringComparison.Ordinal) || context.ChangeTracker.Entries().Any())
            throw new Exception("Packed shared-row delete failed.");
    }

    private static Task<int> Save(DbContext context, bool async)
        => async ? context.SaveChangesAsync() : Task.FromResult(context.SaveChanges());
    private sealed class SplitContext(DbContextOptions<SplitContext> options) : DbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder model)
        {
            model.Entity<Row>().ToTable("SplitRows");
            model.Entity<Row>().Property(r => r.Name).HasMaxLength(40);
            model.Entity<Row>().Property(r => r.Text).HasMaxLength(40);
            model.Entity<Row>().SplitToTable("SplitDetails", t => { t.Property(r => r.Id).HasColumnName("DetailId"); t.Property(r => r.Text); });
            model.Entity<Owner>().ToTable("SharedRows").Property(o => o.Name).HasMaxLength(40);
            model.Entity<Detail>().ToTable("SharedRows").Property(d => d.Text).HasMaxLength(40);
            model.Entity<Owner>().HasOne(o => o.Detail).WithOne(d => d.Owner).HasForeignKey<Detail>(d => d.Id);
        }
    }
    private sealed class Row { public int Id { get; set; } public string? Name { get; set; } public string? Text { get; set; } }
    private sealed class Owner { public int Id { get; set; } public string? Name { get; set; } public Detail? Detail { get; set; } }
    private sealed class Detail { public int Id { get; set; } public string? Text { get; set; } public Owner Owner { get; set; } = null!; }

    private sealed class Commands : DbCommandInterceptor
    {
        public string? Query { get; set; }
        public List<string> Sql { get; } = [];
        public List<object?[]> Inputs { get; } = [];
        private void Capture(DbCommand command)
        {
            Sql.Add(command.CommandText);
            Inputs.Add(command.Parameters.Cast<DbParameter>().Where(p => p.Direction == ParameterDirection.Input).Select(p => p.Value).ToArray());
        }
        public override InterceptionResult<int> NonQueryExecuting(DbCommand command, CommandEventData data, InterceptionResult<int> result)
        {
            Capture(command);
            foreach (DbParameter parameter in command.Parameters)
                if (parameter.Direction == ParameterDirection.Output) parameter.Value = new OceanBaseDecimal(101);
            return InterceptionResult<int>.SuppressWithResult(1);
        }
        public override ValueTask<InterceptionResult<int>> NonQueryExecutingAsync(DbCommand command, CommandEventData data,
            InterceptionResult<int> result, CancellationToken token = default) => ValueTask.FromResult(NonQueryExecuting(command, data, result));
        public override InterceptionResult<DbDataReader> ReaderExecuting(DbCommand command, CommandEventData data, InterceptionResult<DbDataReader> result)
        {
            Capture(command);
            var table = new DataTable();
            var types = Query switch
            {
                "split" => new[] { typeof(int), typeof(string), typeof(string) },
                "shared" => [typeof(int), typeof(string), typeof(int), typeof(string)],
                _ => [typeof(int)]
            };
            foreach (var type in types) table.Columns.Add("C" + table.Columns.Count, type);
            if (Query == "split") table.Rows.Add(101, "row", DBNull.Value);
            else if (Query == "shared") { table.Rows.Add(101, "owner", 101, "detail"); table.Rows.Add(102, "absent", DBNull.Value, DBNull.Value); }
            else table.Rows.Add(101);
            return InterceptionResult<DbDataReader>.SuppressWithResult(table.CreateDataReader());
        }
        public override ValueTask<InterceptionResult<DbDataReader>> ReaderExecutingAsync(DbCommand command, CommandEventData data,
            InterceptionResult<DbDataReader> result, CancellationToken token = default) => ValueTask.FromResult(ReaderExecuting(command, data, result));
    }
    private sealed class NoNetwork : DbConnectionInterceptor
    {
        public override InterceptionResult ConnectionOpening(DbConnection connection, ConnectionEventData data, InterceptionResult result)
            => InterceptionResult.Suppress();
        public override ValueTask<InterceptionResult> ConnectionOpeningAsync(DbConnection connection, ConnectionEventData data,
            InterceptionResult result, CancellationToken token = default) => ValueTask.FromResult(InterceptionResult.Suppress());
    }
}
