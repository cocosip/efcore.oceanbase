using System;
using System.Collections.Generic;
using System.Data.Common;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using OceanBase.EntityFrameworkCore;

namespace PackageConsumer
{
    internal static class SchemaSmoke
    {
        public static void Run(OceanBaseCompatibilityMode mode)
        {
            if (mode == OceanBaseCompatibilityMode.Oracle) VerifyOracleUsers();
            using var context = new SchemaContext(new DbContextOptionsBuilder<SchemaContext>()
                .UseOceanBase("Server=offline;Database=must_not_connect", mode).Options);
            var script = context.Database.GenerateCreateScript();
            var identity = mode == OceanBaseCompatibilityMode.MySql ? "AUTO_INCREMENT" : "GENERATED BY DEFAULT AS IDENTITY";
            var defaultValue = mode == OceanBaseCompatibilityMode.MySql ? "DEFAULT ('can''t')" : "DEFAULT N'can''t'";
            if (!script.Contains(identity, StringComparison.Ordinal) || !script.Contains(defaultValue, StringComparison.Ordinal)
                || !script.Contains("PRIMARY KEY", StringComparison.Ordinal) || !script.Contains("CREATE UNIQUE INDEX", StringComparison.Ordinal))
            {
                throw new Exception("Packed create script lost identity, default, key or index SQL.");
            }
            Console.WriteLine($"{mode}: packed provider offline relational create script passed.");
            foreach (var async in new[] { false, true })
            {
                var capture = new Capture();
                using var managed = new SchemaContext(new DbContextOptionsBuilder<SchemaContext>()
                    .UseOceanBase("Server=offline;Database=owned", mode)
                    .EnableOceanBaseSchemaManagement("owned").AddInterceptors(capture).Options);
                var created = async ? managed.Database.EnsureCreatedAsync().GetAwaiter().GetResult() : managed.Database.EnsureCreated();
                if (!created || capture.Commands.Count != 4
                    || capture.Commands[0] != (mode == OceanBaseCompatibilityMode.MySql ? "SELECT DATABASE()"
                        : "SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') FROM DUAL")
                    || !capture.Commands[1].StartsWith("SELECT COUNT", StringComparison.Ordinal)
                    || !capture.Commands[2].Contains(identity, StringComparison.Ordinal)
                    || !capture.Commands[3].StartsWith("CREATE UNIQUE INDEX", StringComparison.Ordinal))
                    throw new Exception("Packed schema creation lost its scope, emptiness or DDL contract.");
                capture.Commands.Clear();
                capture.HasTables = true;
                created = async ? managed.Database.EnsureCreatedAsync().GetAwaiter().GetResult() : managed.Database.EnsureCreated();
                if (created || capture.Commands.Count != 2)
                    throw new Exception("Packed schema creation changed an existing populated schema.");
            }
            Console.WriteLine($"{mode}: packed provider intercepted sync/async existing-schema creation passed.");
            RunDatabaseManagement(mode);
            if (mode == OceanBaseCompatibilityMode.MySql) RunManagementFactory();
        }

        private static void RunManagementFactory()
        {
            foreach (var async in new[] { false, true })
            {
                var capture = new Capture { NamespaceExists = true };
                using var target = new OceanBaseConnector.OceanBaseConnection("Server=offline;Database=owned");
                var builder = new DbContextOptionsBuilder<SchemaContext>().UseOceanBase(target, OceanBaseCompatibilityMode.MySql)
                    .EnableOceanBaseDatabaseManagement("owned").AddInterceptors(capture);
                OceanBaseConnector.OceanBaseConnection? management = null;
                Func<OceanBaseConnector.OceanBaseConnection> factory = () => management = new("Server=offline;User Id=administrator")
                    { RemoteCertificateValidationCallback = (_, _, _, _) => false };
                var api = typeof(OceanBaseDbContextOptionsBuilderExtensions).GetMethod("UseOceanBaseManagementConnection",
                    [typeof(DbContextOptionsBuilder), typeof(Func<OceanBaseConnector.OceanBaseConnection>)]);
                if (api is null) throw new NotSupportedException("Packed provider has no explicit management connection API.");
                api.Invoke(null, [builder, factory]);
                using (var context = new SchemaContext(builder.Options))
                {
                    capture.Target = target;
                    context.Database.SetCommandTimeout(19);
                    var deleted = async ? context.Database.EnsureDeletedAsync().GetAwaiter().GetResult() : context.Database.EnsureDeleted();
                    if (!deleted || capture.Commands.Count != 2 || capture.Commands[1] != "DROP DATABASE `owned`"
                        || management?.RemoteCertificateValidationCallback is null || capture.Management != management)
                        throw new Exception("Packed provider lost explicit management connection routing or deletion.");
                }
                try
                {
                    using var command = management!.CreateCommand();
                    throw new Exception("Packed provider did not dispose its owned management connection.");
                }
                catch (ObjectDisposedException) { }
                using var targetCommand = target.CreateCommand();
            }
            Console.WriteLine("MySQL: packed explicit management connection and supplied-target ownership passed.");
        }

        private static void RunDatabaseManagement(OceanBaseCompatibilityMode mode)
        {
            foreach (var async in new[] { false, true })
            {
                var capture = new Capture();
                using var context = new SchemaContext(new DbContextOptionsBuilder<SchemaContext>()
                    .UseOceanBase("Server=offline;Database=owned", mode)
                    .EnableOceanBaseDatabaseManagement("owned").AddInterceptors(capture).Options);
                capture.Target = context.Database.GetDbConnection();
                if (mode == OceanBaseCompatibilityMode.Oracle)
                {
                    try
                    {
                        if (async) context.Database.EnsureDeletedAsync().GetAwaiter().GetResult();
                        else context.Database.EnsureDeleted();
                        throw new Exception("Packed provider allowed unsupported Oracle namespace deletion.");
                    }
                    catch (NotSupportedException) { }
                    if (capture.Opens != 0) throw new Exception("Oracle namespace rejection opened a connection.");
                    continue;
                }
                var created = async ? context.Database.EnsureCreatedAsync().GetAwaiter().GetResult() : context.Database.EnsureCreated();
                if (!created || capture.Commands.Count != 5 || capture.Commands[1] != "CREATE DATABASE `owned`"
                    || capture.Commands[2] != "SELECT DATABASE()"
                    || !capture.Commands[3].StartsWith("CREATE TABLE", StringComparison.Ordinal)
                    || !capture.Commands[4].StartsWith("CREATE UNIQUE INDEX", StringComparison.Ordinal))
                    throw new Exception("Packed provider lost namespace-before-table creation.");
                capture.Commands.Clear();
                var deleted = async ? context.Database.EnsureDeletedAsync().GetAwaiter().GetResult() : context.Database.EnsureDeleted();
                if (!deleted || capture.Commands.Count != 2 || capture.Commands[1] != "DROP DATABASE `owned`"
                    || capture.Target.Database != "owned")
                    throw new Exception("Packed provider lost owned namespace deletion or changed the target.");
                capture.Commands.Clear();
                capture.Opens = 0;
                ((OceanBaseConnector.OceanBaseConnection)capture.Target).ConnectionString = "Server=other;Database=owned";
                try
                {
                    if (async) context.Database.EnsureDeletedAsync().GetAwaiter().GetResult();
                    else context.Database.EnsureDeleted();
                    throw new Exception("Packed provider accepted a stale management server configuration.");
                }
                catch (NotSupportedException) { }
                if (capture.Opens != 0 || capture.Commands.Count != 0)
                    throw new Exception("Unsafe management configuration reached connection execution.");
            }
            Console.WriteLine($"{mode}: packed provider namespace ownership and management connection guards passed.");
        }

        private static void VerifyOracleUsers()
        {
            foreach (var async in new[] { false, true })
            {
                var capture = new Capture();
                var messages = new List<string>();
                var passwordCalls = 0;
                using var target = new OceanBaseConnector.OceanBaseConnection("Server=offline;User Id=owned@tenant");
                OceanBaseConnector.OceanBaseConnection? management = null;
                using (var context = new SchemaContext(new DbContextOptionsBuilder<SchemaContext>()
                    .UseOceanBase(target, OceanBaseCompatibilityMode.Oracle)
                    .EnableOceanBaseUserManagement("owned", () => { passwordCalls++; return "synthetic-private-password"; })
                    .UseOceanBaseManagementConnection(() => management = new OceanBaseConnector.OceanBaseConnection("Server=offline;User Id=administrator@tenant"))
                    .AddInterceptors(capture).LogTo(messages.Add).EnableServiceProviderCaching(false).Options))
                {
                    capture.Target = target;
                    var created = async ? context.Database.EnsureCreatedAsync().GetAwaiter().GetResult() : context.Database.EnsureCreated();
                    if (!created || passwordCalls != 1 || capture.Commands[1] != "CREATE USER \"owned\" IDENTIFIED BY \"synthetic-private-password\""
                        || capture.Commands[2] != "GRANT CREATE SESSION, CREATE TABLE TO \"owned\"")
                        throw new Exception("Packed Oracle user creation/grants failed.");
                    if (string.Join("\n", messages).Contains("synthetic-private-password", StringComparison.Ordinal)
                        || !string.Join("\n", messages).Contains("IDENTIFIED BY <redacted>", StringComparison.Ordinal))
                        throw new Exception("Packed Oracle credential logging was not redacted.");
                    var deleted = async ? context.Database.EnsureDeletedAsync().GetAwaiter().GetResult() : context.Database.EnsureDeleted();
                    if (!deleted || passwordCalls != 1 || capture.Commands[^1] != "DROP USER \"owned\" CASCADE")
                        throw new Exception("Packed Oracle user deletion failed.");
                }
                using var stillUsable = target.CreateCommand();
                try { using var invalid = management!.CreateCommand(); throw new Exception("Packed management connection was not disposed."); }
                catch (ObjectDisposedException) { }
            }
            Console.WriteLine("Oracle: packed owned user lifecycle and credential log redaction passed.");
        }

        private sealed class Capture : DbConnectionInterceptor, IDbCommandInterceptor
        {
            public DbConnection? Management { get; private set; }
            public List<string> Commands { get; } = [];
            public bool HasTables { get; set; }
            public bool NamespaceExists { get; set; }
            public DbConnection? Target { get; set; }
            public int Opens { get; set; }
            public override InterceptionResult ConnectionOpening(DbConnection connection, ConnectionEventData eventData, InterceptionResult result)
            { Opens++; return InterceptionResult.Suppress(); }
            public override ValueTask<InterceptionResult> ConnectionOpeningAsync(DbConnection connection, ConnectionEventData eventData,
                InterceptionResult result, CancellationToken cancellationToken = default)
                => ValueTask.FromResult(ConnectionOpening(connection, eventData, result));
            public InterceptionResult<object> ScalarExecuting(DbCommand command, CommandEventData eventData, InterceptionResult<object> result)
            {
                Commands.Add(command.CommandText);
                if (command.CommandText.StartsWith("SELECT USERNAME", StringComparison.Ordinal))
                {
                    VerifyManagementConnection(command);
                    if (command.Parameters.Count != 1 || !Equals(command.Parameters[0].Value, "owned"))
                        throw new Exception("Packed Oracle catalog scope was not bound.");
                    return InterceptionResult<object>.SuppressWithResult(NamespaceExists ? "owned" : DBNull.Value);
                }
                if (command.CommandText.StartsWith("SELECT SCHEMA_NAME", StringComparison.Ordinal))
                {
                    VerifyManagementConnection(command);
                    if (!command.CommandText.EndsWith("SCHEMA_NAME = ?", StringComparison.Ordinal)
                        || command.Parameters.Count != 1 || !Equals(command.Parameters[0].Value, "owned"))
                        throw new Exception("Packed namespace probe did not bind its scope.");
                    return InterceptionResult<object>.SuppressWithResult(NamespaceExists ? "owned" : DBNull.Value);
                }
                return InterceptionResult<object>.SuppressWithResult(command.CommandText.StartsWith("SELECT COUNT", StringComparison.Ordinal)
                    ? HasTables ? 1 : 0 : "owned");
            }
            public ValueTask<InterceptionResult<object>> ScalarExecutingAsync(DbCommand command, CommandEventData eventData,
                InterceptionResult<object> result, CancellationToken cancellationToken = default)
                => ValueTask.FromResult(ScalarExecuting(command, eventData, result));
            public InterceptionResult<int> NonQueryExecuting(DbCommand command, CommandEventData eventData, InterceptionResult<int> result)
            {
                Commands.Add(command.CommandText);
                if (command.CommandText.StartsWith("CREATE DATABASE", StringComparison.Ordinal)
                    || command.CommandText.StartsWith("DROP DATABASE", StringComparison.Ordinal)
                    || command.CommandText.StartsWith("CREATE USER", StringComparison.Ordinal)
                    || command.CommandText.StartsWith("DROP USER", StringComparison.Ordinal))
                {
                    VerifyManagementConnection(command);
                    NamespaceExists = command.CommandText.StartsWith("CREATE", StringComparison.Ordinal);
                }
                return InterceptionResult<int>.SuppressWithResult(0);
            }
            private void VerifyManagementConnection(DbCommand command)
            {
                Management = command.Connection;
                if (command.Connection is null || ReferenceEquals(command.Connection, Target) || command.Connection.Database != "")
                    throw new Exception("Packed namespace command did not use an independent connection without a database.");
            }
            public ValueTask<InterceptionResult<int>> NonQueryExecutingAsync(DbCommand command, CommandEventData eventData,
                InterceptionResult<int> result, CancellationToken cancellationToken = default)
                => ValueTask.FromResult(NonQueryExecuting(command, eventData, result));
        }

        private sealed class SchemaContext(DbContextOptions<SchemaContext> options) : DbContext(options)
        {
            protected override void OnModelCreating(ModelBuilder modelBuilder)
            {
                modelBuilder.Entity<Row>().ToTable("ScriptRows");
                modelBuilder.Entity<Row>().Property(r => r.Name).HasMaxLength(40).HasDefaultValue("can't");
                modelBuilder.Entity<Row>().HasIndex(r => r.Name).IsUnique();
            }
        }

        private sealed class Row { public int Id { get; set; } public string Name { get; set; } = ""; }
    }
}
