using System;
using System.Collections.Generic;
using System.Data;
using System.Data.Common;
using System.Linq;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using OceanBase.EntityFrameworkCore;
using OceanBaseDecimal = OceanBaseConnector.OceanBaseDecimal;

namespace PackageConsumer;

internal static class TptSmoke
{
    public static void Run(OceanBaseCompatibilityMode mode)
    {
        foreach (var async in new[] { false, true }) RunAsync(mode, async).GetAwaiter().GetResult();
        Console.WriteLine($"{mode}: packed TPT schema/model differences, materialization and multi-table CRUD passed (offline).");
    }

    private static async Task RunAsync(OceanBaseCompatibilityMode mode, bool async)
    {
        var capture = new Commands();
        await using var context = new HierarchyContext(new DbContextOptionsBuilder<HierarchyContext>()
            .UseOceanBase("Server=offline.invalid;Database=package_smoke", mode)
            .EnableServiceProviderCaching(false).AddInterceptors(new NoNetwork(), capture).Options);
        // Command interception has no native transaction; automatic transaction behavior is covered in source tests.
        context.Database.AutoTransactionBehavior = AutoTransactionBehavior.Never;
        var script = context.Database.GenerateCreateScript();
        var model = context.GetService<IDesignTimeModel>().Model;
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        var migrated = string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(operations, model).Select(c => c.CommandText));
        foreach (var sql in new[] { script, migrated })
            if (Regex.Matches(sql, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY").Count != 1
                || Regex.Matches(sql, "FOREIGN KEY").Count != 2)
                throw new Exception("Packed TPT schema lost its single root identity or hierarchy foreign keys.");
        var query = context.Set<Sensor>();
        capture.ReadRows = true;
        var materialized = async ? await query.SingleAsync() : query.Single();
        if (materialized.Id != 101 || materialized.Name != "sensor" || materialized.Serial != 7 || materialized.Reading is not null
            || !capture.Sql.Single().Contains("INNER JOIN", StringComparison.Ordinal))
            throw new Exception("Packed TPT materialization failed.");
        context.ChangeTracker.Clear();
        capture.ReadRows = false;
        capture.Sql.Clear();
        capture.Inputs.Clear();
        var sensor = new Sensor { Name = "new", Serial = 7, Reading = 2 };
        context.Add(sensor);
        if ((async ? await context.SaveChangesAsync() : context.SaveChanges()) != 3 || sensor.Id != 101
            || !capture.Sql[0].Contains("INSERT INTO", StringComparison.Ordinal)
            || !capture.Inputs.Skip(1).Where(values => values.Length > 0).All(values => values.Contains(101)))
            throw new Exception("Packed TPT generated key propagation failed.");
        capture.Sql.Clear();
        sensor.Name = "changed";
        sensor.Reading = null;
        if ((async ? await context.SaveChangesAsync() : context.SaveChanges()) != 2
            || capture.Sql.Count != 2 || capture.Sql.Any(sql => !sql.StartsWith("UPDATE", StringComparison.Ordinal)))
            throw new Exception("Packed TPT owning-table updates failed.");
        capture.Sql.Clear();
        context.Remove(sensor);
        if ((async ? await context.SaveChangesAsync() : context.SaveChanges()) != 3
            || !capture.Sql[0].Contains("SensorRows", StringComparison.Ordinal)
            || !capture.Sql[2].Contains("AssetRows", StringComparison.Ordinal)
            || context.ChangeTracker.Entries().Any())
            throw new Exception("Packed TPT reverse dependency deletion failed.");
    }

    private sealed class HierarchyContext(DbContextOptions<HierarchyContext> options) : DbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder model)
        {
            model.Entity<Asset>().UseTptMappingStrategy().ToTable("AssetRows");
            model.Entity<Asset>().Property(a => a.Name).HasMaxLength(40);
            model.Entity<Device>().ToTable("DeviceRows");
            model.Entity<Sensor>().ToTable("SensorRows");
        }
    }
    private abstract class Asset { public int Id { get; set; } public string? Name { get; set; } }
    private class Device : Asset { public int Serial { get; set; } }
    private sealed class Sensor : Device { public int? Reading { get; set; } }

    private sealed class Commands : DbCommandInterceptor
    {
        public bool ReadRows { get; set; }
        public List<string> Sql { get; } = [];
        public List<object?[]> Inputs { get; } = [];
        private void Capture(DbCommand command)
        {
            Sql.Add(command.CommandText);
            Inputs.Add(command.Parameters.Cast<DbParameter>().Where(p => p.Direction == ParameterDirection.Input).Select(p => p.Value).ToArray());
        }
        public override InterceptionResult<int> NonQueryExecuting(DbCommand command, CommandEventData data, InterceptionResult<int> result)
        {
            Capture(command);
            foreach (DbParameter parameter in command.Parameters)
                if (parameter.Direction == ParameterDirection.Output) parameter.Value = new OceanBaseDecimal(101);
            return InterceptionResult<int>.SuppressWithResult(1);
        }
        public override ValueTask<InterceptionResult<int>> NonQueryExecutingAsync(DbCommand command, CommandEventData data,
            InterceptionResult<int> result, CancellationToken token = default) => ValueTask.FromResult(NonQueryExecuting(command, data, result));
        public override InterceptionResult<DbDataReader> ReaderExecuting(DbCommand command, CommandEventData data, InterceptionResult<DbDataReader> result)
        {
            Capture(command);
            var table = new DataTable();
            table.Columns.Add("Id", typeof(int));
            if (ReadRows)
            {
                table.Columns.Add("Name", typeof(string));
                table.Columns.Add("Serial", typeof(int));
                table.Columns.Add("Reading", typeof(int));
                table.Rows.Add(101, "sensor", 7, DBNull.Value);
            }
            else table.Rows.Add(101);
            return InterceptionResult<DbDataReader>.SuppressWithResult(table.CreateDataReader());
        }
        public override ValueTask<InterceptionResult<DbDataReader>> ReaderExecutingAsync(DbCommand command, CommandEventData data,
            InterceptionResult<DbDataReader> result, CancellationToken token = default) => ValueTask.FromResult(ReaderExecuting(command, data, result));
    }
    private sealed class NoNetwork : DbConnectionInterceptor
    {
        public override InterceptionResult ConnectionOpening(DbConnection connection, ConnectionEventData data, InterceptionResult result)
            => InterceptionResult.Suppress();
        public override ValueTask<InterceptionResult> ConnectionOpeningAsync(DbConnection connection, ConnectionEventData data,
            InterceptionResult result, CancellationToken token = default) => ValueTask.FromResult(InterceptionResult.Suppress());
    }
}
