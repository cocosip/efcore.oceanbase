using System;
using System.Collections.Generic;
using System.Data;
using System.Data.Common;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Storage;
using Xunit;

namespace OceanBase.EntityFrameworkCore.FunctionalTests
{
    public sealed class SchemaLifecycleTests
    {
        public static IEnumerable<object[]> Modes()
        {
            foreach (var mode in Enum.GetValues<OceanBaseCompatibilityMode>())
                foreach (var async in new[] { false, true }) yield return [mode, async];
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task EnsureCreated_checks_scope_then_tables_and_executes_the_create_plan(OceanBaseCompatibilityMode mode, bool async)
        {
            var capture = new Capture();
            await using var context = Create(mode, capture);
            context.Database.SetCommandTimeout(21);
            using var source = new CancellationTokenSource();
            Assert.True(async ? await context.Database.EnsureCreatedAsync(source.Token) : context.Database.EnsureCreated());
            Assert.Equal(3, capture.Commands.Count);
            Assert.Equal(mode == OceanBaseCompatibilityMode.MySql ? "SELECT DATABASE()"
                : "SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') FROM DUAL", capture.Commands[0].Sql);
            Assert.StartsWith("SELECT COUNT(*)", capture.Commands[1].Sql);
            Assert.StartsWith("CREATE TABLE", capture.Commands[2].Sql);
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "AUTO_INCREMENT" : "GENERATED BY DEFAULT AS IDENTITY", capture.Commands[2].Sql);
            Assert.All(capture.Commands, c =>
            {
                Assert.Equal(async, c.Async);
                Assert.Null(c.Transaction);
                Assert.Equal(21, c.Timeout);
                if (async) Assert.Equal(source.Token, c.Token);
            });
            AssertBalanced(context);
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Existing_tables_are_not_modified(OceanBaseCompatibilityMode mode, bool async)
        {
            var capture = new Capture { HasTables = true };
            await using var context = Create(mode, capture);
            Assert.False(async ? await context.Database.EnsureCreatedAsync() : context.Database.EnsureCreated());
            Assert.Equal(2, capture.Commands.Count);
            Assert.All(capture.Commands, c => Assert.StartsWith("SELECT", c.Sql));
            AssertBalanced(context);
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Explicit_CreateTables_uses_the_same_scope_and_plan_without_the_emptiness_probe(OceanBaseCompatibilityMode mode, bool async)
        {
            var capture = new Capture();
            await using var context = Create(mode, capture);
            var connection = context.GetService<IRelationalConnection>();
            if (async) await connection.OpenAsync(CancellationToken.None);
            else connection.Open();
            var creator = context.GetService<IRelationalDatabaseCreator>();
            if (async) await creator.CreateTablesAsync();
            else creator.CreateTables();
            Assert.Equal(2, capture.Commands.Count);
            Assert.StartsWith("CREATE TABLE", capture.Commands[1].Sql);
            Assert.Equal(1, OpenCount(connection));
            if (async) await connection.CloseAsync();
            else connection.Close();
            AssertBalanced(context);
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Missing_opt_in_and_cross_scope_models_reject_before_open(OceanBaseCompatibilityMode mode, bool async)
        {
            foreach (var shape in new[] { "no-opt-in", "cross-scope", "cross-scope-principal" })
            {
                var capture = new Capture();
                await using var context = Create(mode, capture, shape);
                if (async) await Assert.ThrowsAsync<NotSupportedException>(() => context.Database.EnsureCreatedAsync());
                else Assert.Throws<NotSupportedException>(() => context.Database.EnsureCreated());
                Assert.Empty(capture.Commands);
                Assert.Equal(0, capture.Opens);
            }
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Mismatched_current_scope_never_executes_DDL(OceanBaseCompatibilityMode mode, bool async)
        {
            var capture = new Capture { Scope = "other" };
            await using var context = Create(mode, capture);
            if (async) await Assert.ThrowsAsync<InvalidOperationException>(() => context.Database.EnsureCreatedAsync());
            else Assert.Throws<InvalidOperationException>(() => context.Database.EnsureCreated());
            Assert.Single(capture.Commands);
            AssertBalanced(context);
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task DDL_failure_retains_the_original_error_and_balances_the_lease(OceanBaseCompatibilityMode mode, bool async)
        {
            var failure = new InvalidOperationException("synthetic DDL failure");
            var capture = new Capture { Failure = failure };
            await using var context = Create(mode, capture);
            var actual = async ? await Assert.ThrowsAsync<InvalidOperationException>(() => context.Database.EnsureCreatedAsync())
                : Assert.Throws<InvalidOperationException>(() => context.Database.EnsureCreated());
            Assert.Same(failure, actual);
            Assert.Equal(3, capture.Commands.Count);
            Assert.DoesNotContain(capture.Commands, c => c.Sql.StartsWith("DROP", StringComparison.Ordinal));
            AssertBalanced(context);
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Ambient_transactions_are_rejected_before_open(OceanBaseCompatibilityMode mode, bool async)
        {
            var capture = new Capture();
            await using var context = Create(mode, capture);
            using (var transaction = new System.Transactions.TransactionScope(System.Transactions.TransactionScopeAsyncFlowOption.Enabled))
            {
                if (async) await Assert.ThrowsAsync<NotSupportedException>(() => context.Database.EnsureCreatedAsync());
                else Assert.Throws<NotSupportedException>(() => context.Database.EnsureCreated());
            }
            Assert.Equal(0, capture.Opens);
            Assert.Empty(capture.Commands);
        }

        [Theory]
        [InlineData(OceanBaseCompatibilityMode.MySql)]
        [InlineData(OceanBaseCompatibilityMode.Oracle)]
        public async Task Precancelled_creation_does_not_open_or_execute(OceanBaseCompatibilityMode mode)
        {
            var capture = new Capture();
            await using var context = Create(mode, capture);
            using var source = new CancellationTokenSource();
            source.Cancel();
            var error = await Assert.ThrowsAnyAsync<OperationCanceledException>(() => context.Database.EnsureCreatedAsync(source.Token));
            Assert.Equal(source.Token, error.CancellationToken);
            Assert.Equal(0, capture.Opens);
            Assert.Empty(capture.Commands);
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Empty_models_do_not_open_and_qualified_tables_stay_in_scope(OceanBaseCompatibilityMode mode, bool async)
        {
            var capture = new Capture();
            await using (var empty = Create(mode, capture, "empty"))
                Assert.False(async ? await empty.Database.EnsureCreatedAsync() : empty.Database.EnsureCreated());
            Assert.Equal(0, capture.Opens);
            await using var qualified = Create(mode, capture, "qualified");
            Assert.True(async ? await qualified.Database.EnsureCreatedAsync() : qualified.Database.EnsureCreated());
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "`owned`.`Rows`" : "\"owned\".\"Rows\"", capture.Commands[2].Sql);
            AssertBalanced(qualified);
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Partial_DDL_failure_and_cleanup_failure_keep_the_primary_error(OceanBaseCompatibilityMode mode, bool async)
        {
            foreach (var cancelled in new[] { false, true })
            {
                using var source = new CancellationTokenSource();
                Exception failure = cancelled ? new OperationCanceledException(source.Token) : new InvalidOperationException("DDL failed");
                var cleanup = new InvalidOperationException("cleanup failed");
                var capture = new Capture { Failure = failure, FailOnDdl = 2, BeforeFailure = cancelled ? source.Cancel : null };
                await using var context = Create(mode, capture, "cleanup");
                var connection = Assert.IsType<CleanupConnection>(context.GetService<IRelationalConnection>());
                connection.Failure = cleanup;
                var actual = await Record.ExceptionAsync(async () =>
                {
                    if (async) await context.Database.EnsureCreatedAsync(source.Token);
                    else context.Database.EnsureCreated();
                });
                Assert.Same(failure, actual);
                Assert.Equal(cancelled, source.IsCancellationRequested);
                Assert.Same(cleanup, actual!.Data["OceanBase.SchemaCleanupError"]);
                Assert.Equal(4, capture.Commands.Count);
                Assert.Equal(2, capture.Commands.Count(c => c.Sql.StartsWith("CREATE TABLE", StringComparison.Ordinal)));
                Assert.DoesNotContain(capture.Commands, c => c.Sql.StartsWith("DROP", StringComparison.Ordinal));
                AssertBalanced(context);
            }
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Successful_DDL_does_not_hide_cleanup_failure(OceanBaseCompatibilityMode mode, bool async)
        {
            var capture = new Capture();
            await using var context = Create(mode, capture, "cleanup");
            var failure = new InvalidOperationException("cleanup failed");
            Assert.IsType<CleanupConnection>(context.GetService<IRelationalConnection>()).Failure = failure;
            var actual = async ? await Assert.ThrowsAsync<InvalidOperationException>(() => context.Database.EnsureCreatedAsync())
                : Assert.Throws<InvalidOperationException>(() => context.Database.EnsureCreated());
            Assert.Same(failure, actual);
            AssertBalanced(context);
        }

        [Theory]
        [MemberData(nameof(Modes))]
        public async Task Caller_transaction_is_preserved_and_rejected_before_schema_commands(OceanBaseCompatibilityMode mode, bool async)
        {
            var capture = new Capture();
            await using var context = Create(mode, capture);
            using var native = new CallerTransaction(context.Database.GetDbConnection());
            await using var transaction = context.Database.UseTransaction(native)!;
            var opens = capture.Opens;
            if (async) await Assert.ThrowsAsync<NotSupportedException>(() => context.Database.EnsureCreatedAsync());
            else Assert.Throws<NotSupportedException>(() => context.Database.EnsureCreated());
            Assert.Same(transaction, context.Database.CurrentTransaction);
            Assert.Equal(opens, capture.Opens);
            Assert.Empty(capture.Commands);
            Assert.Equal(1, OpenCount(context.GetService<IRelationalConnection>()));
        }

        private sealed class CallerTransaction(DbConnection connection) : DbTransaction
        {
            public override IsolationLevel IsolationLevel => IsolationLevel.ReadCommitted;
            protected override DbConnection DbConnection => connection;
            public override void Commit() => throw new InvalidOperationException("Must not commit caller transaction.");
            public override void Rollback() => throw new InvalidOperationException("Must not roll back caller transaction.");
        }

        private static TestContext Create(OceanBaseCompatibilityMode mode, Capture capture, string shape = "ordinary")
        {
            var builder = new DbContextOptionsBuilder<TestContext>().UseOceanBase("Server=offline;Database=owned", mode)
                .AddInterceptors(capture).ReplaceService<IModelCacheKeyFactory, ShapeKey>();
            if (shape != "no-opt-in") builder.EnableOceanBaseSchemaManagement("owned");
            if (shape == "cleanup") builder.ReplaceService<IRelationalConnection, CleanupConnection>();
            return new TestContext(builder.Options, shape);
        }

        public sealed class CleanupConnection(RelationalConnectionDependencies dependencies) : RelationalConnection(dependencies)
        {
            public Exception? Failure { get; set; }
            protected override DbConnection CreateDbConnection() => new OceanBaseConnector.OceanBaseConnection(ConnectionString!);
            public override bool Close()
            {
                var result = base.Close();
                CheckFailure();
                return result;
            }
            public override async Task<bool> CloseAsync()
            {
                var result = await base.CloseAsync();
                CheckFailure();
                return result;
            }
            private void CheckFailure()
            {
                if (OpenCount(this) == 0 && Failure is { } error)
                {
                    Failure = null;
                    throw error;
                }
            }
        }

        private static int OpenCount(IRelationalConnection connection)
            => (int)typeof(RelationalConnection).GetField("_openedCount", System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic)!.GetValue(connection)!;

        private static void AssertBalanced(DbContext context) => Assert.Equal(0, OpenCount(context.GetService<IRelationalConnection>()));

        public sealed class ShapeKey(ModelCacheKeyFactoryDependencies dependencies) : ModelCacheKeyFactory(dependencies)
        {
            public override object Create(DbContext context, bool designTime) => (base.Create(context, designTime), ((TestContext)context).Shape);
        }

        private sealed class TestContext(DbContextOptions<TestContext> options, string shape) : DbContext(options)
        {
            public string Shape => shape;
            protected override void OnModelCreating(ModelBuilder modelBuilder)
            {
                if (shape == "empty") return;
                modelBuilder.Entity<Row>().ToTable("Rows", shape == "cross-scope" ? "other" : shape == "qualified" ? "owned" : null);
                modelBuilder.Entity<Row>().Property(r => r.Name).HasMaxLength(40);
                if (shape is "cleanup" or "cross-scope-principal")
                {
                    modelBuilder.Entity<Principal>().ToTable("Principals", shape == "cross-scope-principal" ? "other" : null,
                        t => t.ExcludeFromMigrations(shape == "cross-scope-principal"));
                    modelBuilder.Entity<Row>().HasOne<Principal>().WithMany().HasForeignKey("PrincipalId");
                }
            }
        }
        private sealed class Principal { public int Id { get; set; } }
        private sealed class Row { public int Id { get; set; } public string Name { get; set; } = ""; }
        private sealed record Command(string Sql, bool Async, CancellationToken Token, DbTransaction? Transaction, int Timeout);

        private sealed class Capture : DbConnectionInterceptor, IDbCommandInterceptor
        {
            public List<Command> Commands { get; } = [];
            public string Scope { get; init; } = "owned";
            public bool HasTables { get; init; }
            public Exception? Failure { get; init; }
            public int FailOnDdl { get; init; } = 1;
            public Action? BeforeFailure { get; init; }
            private int _ddl;
            public int Opens { get; private set; }
            public override InterceptionResult ConnectionOpening(DbConnection connection, ConnectionEventData eventData, InterceptionResult result)
            { Opens++; return InterceptionResult.Suppress(); }
            public override ValueTask<InterceptionResult> ConnectionOpeningAsync(DbConnection connection, ConnectionEventData eventData,
                InterceptionResult result, CancellationToken cancellationToken = default)
                => ValueTask.FromResult(ConnectionOpening(connection, eventData, result));
            public InterceptionResult<object> ScalarExecuting(DbCommand command, CommandEventData eventData, InterceptionResult<object> result)
                => Scalar(command, false, default);
            public ValueTask<InterceptionResult<object>> ScalarExecutingAsync(DbCommand command, CommandEventData eventData,
                InterceptionResult<object> result, CancellationToken cancellationToken = default)
                => ValueTask.FromResult(Scalar(command, true, cancellationToken));
            private InterceptionResult<object> Scalar(DbCommand command, bool async, CancellationToken token)
            {
                Record(command, async, token);
                return InterceptionResult<object>.SuppressWithResult(command.CommandText.StartsWith("SELECT COUNT", StringComparison.Ordinal)
                    ? HasTables ? 1 : 0 : Scope);
            }
            public InterceptionResult<int> NonQueryExecuting(DbCommand command, CommandEventData eventData, InterceptionResult<int> result)
                => Execute(command, false, default);
            public ValueTask<InterceptionResult<int>> NonQueryExecutingAsync(DbCommand command, CommandEventData eventData,
                InterceptionResult<int> result, CancellationToken cancellationToken = default)
                => ValueTask.FromResult(Execute(command, true, cancellationToken));
            private InterceptionResult<int> Execute(DbCommand command, bool async, CancellationToken token)
            {
                Record(command, async, token);
                if (++_ddl == FailOnDdl && Failure is not null)
                {
                    BeforeFailure?.Invoke();
                    throw Failure;
                }
                return InterceptionResult<int>.SuppressWithResult(0);
            }
            private void Record(DbCommand command, bool async, CancellationToken token)
                => Commands.Add(new Command(command.CommandText, async, token, command.Transaction, command.CommandTimeout));
        }
    }
}
