using System;
using System.Linq;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using OceanBase.EntityFrameworkCore.Metadata;
using Xunit;

namespace OceanBase.EntityFrameworkCore.UnitTests;

public sealed class TptSchemaTests
{
    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql, false)]
    [InlineData(OceanBaseCompatibilityMode.MySql, true)]
    [InlineData(OceanBaseCompatibilityMode.Oracle, false)]
    [InlineData(OceanBaseCompatibilityMode.Oracle, true)]
    public void Create_scripts_generate_only_the_root_identity(OceanBaseCompatibilityMode mode, bool wide)
    {
        if (wide) CheckCreate<long>(mode);
        else CheckCreate<int>(mode);
    }

    private static void CheckCreate<T>(OceanBaseCompatibilityMode mode) where T : struct
    {
        using var context = Create<T>(mode);
        var script = context.Database.GenerateCreateScript();
        Assert.Equal(4, Regex.Matches(script, "CREATE TABLE").Count);
        Assert.Equal(3, Regex.Matches(script, "FOREIGN KEY").Count);
        Assert.Contains("IX_Leaf_Reading", script);
        Assert.Single(Regex.Matches(script, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY"));
        var root = script.Split(";", StringSplitOptions.RemoveEmptyEntries).Single(s => s.Contains("CREATE TABLE") && s.Contains("RootRows"));
        Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "AUTO_INCREMENT" : "AS IDENTITY", root);
        Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "`app`.`RootRows`" : "\"app\".\"RootRows\"", script);
        foreach (var table in new[] { "MiddleRows", "LeafRows", "SiblingRows" })
        {
            var definition = script.Split(";").Single(s => s.Contains("CREATE TABLE") && s.Contains(table));
            Assert.DoesNotContain("IDENTITY", definition);
            Assert.DoesNotContain("AUTO_INCREMENT", definition);
            Assert.Contains("NOT NULL", definition);
        }
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql, false)]
    [InlineData(OceanBaseCompatibilityMode.MySql, true)]
    [InlineData(OceanBaseCompatibilityMode.Oracle, false)]
    [InlineData(OceanBaseCompatibilityMode.Oracle, true)]
    public void Model_differences_keep_physical_generation_and_evolve_derived_tables(OceanBaseCompatibilityMode mode, bool wide)
    {
        if (wide) CheckMigrations<long>(mode);
        else CheckMigrations<int>(mode);
    }

    private static void CheckMigrations<T>(OceanBaseCompatibilityMode mode) where T : struct
    {
        using var context = Create<T>(mode);
        using var evolvedContext = Create<T>(mode, expanded: true);
        var model = context.GetService<IDesignTimeModel>().Model;
        var evolved = evolvedContext.GetService<IDesignTimeModel>().Model;
        var differ = context.GetService<IMigrationsModelDiffer>();
        var operations = differ.GetDifferences(null, model.GetRelationalModel());
        var creates = operations.OfType<CreateTableOperation>().ToArray();
        Assert.Equal(4, creates.Length);
        foreach (var table in creates)
            Assert.Equal(table.Name == "RootRows", table.Columns.Single(c => c.Name == "Id")
                [OceanBaseRelationalAnnotationProvider.IdentityAnnotation] is true);
        var generator = context.GetService<IMigrationsSqlGenerator>();
        var sql = string.Concat(generator.Generate(operations, model).Select(c => c.CommandText));
        Assert.Single(Regex.Matches(sql, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY"));
        Assert.Equal(3, Regex.Matches(sql, "FOREIGN KEY").Count);
        var changes = differ.GetDifferences(model.GetRelationalModel(), evolved.GetRelationalModel());
        var add = Assert.Single(changes.OfType<AddColumnOperation>());
        Assert.Equal("LeafRows", add.Table);
        Assert.Equal("Revision", add.Name);
        Assert.True(add.IsNullable);
        Assert.Contains("ADD", string.Concat(generator.Generate(changes, evolved).Select(c => c.CommandText)));
        var reverse = differ.GetDifferences(evolved.GetRelationalModel(), model.GetRelationalModel());
        Assert.Equal("LeafRows", Assert.Single(reverse.OfType<DropColumnOperation>()).Table);
        Assert.Contains("DROP COLUMN", string.Concat(generator.Generate(reverse, model).Select(c => c.CommandText)));
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Assigned_composite_and_client_Guid_keys_do_not_create_identities(OceanBaseCompatibilityMode mode)
    {
        CheckNoIdentity<int>(mode, composite: false);
        CheckNoIdentity<int>(mode, composite: true);
        CheckNoIdentity<Guid>(mode, composite: false);
    }

    private static void CheckNoIdentity<T>(OceanBaseCompatibilityMode mode, bool composite) where T : struct
    {
        using var context = Create<T>(mode, assigned: typeof(T) != typeof(Guid), composite: composite);
        var script = context.Database.GenerateCreateScript();
        Assert.DoesNotContain("AUTO_INCREMENT", script);
        Assert.DoesNotContain("IDENTITY", script);
        var model = context.GetService<IDesignTimeModel>().Model;
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        var sql = string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(operations, model).Select(c => c.CommandText));
        Assert.DoesNotContain("AUTO_INCREMENT", sql);
        Assert.DoesNotContain("IDENTITY", sql);
        Assert.All(model.GetRelationalModel().Tables, table => Assert.Equal(composite ? 2 : 1, table.PrimaryKey!.Columns.Count));
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Same_table_names_in_distinct_schemas_do_not_share_identity_generation(OceanBaseCompatibilityMode mode)
    {
        using var context = new HierarchyContext<int>(new DbContextOptionsBuilder<HierarchyContext<int>>()
            .UseOceanBase("Server=offline;Database=app", mode).EnableServiceProviderCaching(false).Options,
            false, false, false, crossSchema: true);
        var script = context.Database.GenerateCreateScript();
        Assert.Single(Regex.Matches(script, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY"));
        var model = context.GetService<IDesignTimeModel>().Model;
        var creates = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel())
            .OfType<CreateTableOperation>().Where(t => t.Name == "SameRows").ToArray();
        Assert.Equal(2, creates.Length);
        Assert.True(creates.Single(t => t.Schema == "root").Columns.Single(c => c.Name == "Id")
            [OceanBaseRelationalAnnotationProvider.IdentityAnnotation] is true);
        Assert.False(creates.Single(t => t.Schema == "child").Columns.Single(c => c.Name == "Id")
            [OceanBaseRelationalAnnotationProvider.IdentityAnnotation] is true);
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Tpt_does_not_admit_unbacked_generated_nonkeys(OceanBaseCompatibilityMode mode)
    {
        using var context = new HierarchyContext<int>(new DbContextOptionsBuilder<HierarchyContext<int>>()
            .UseOceanBase("Server=offline;Database=app", mode).EnableOceanBaseSchemaManagement("app")
            .EnableServiceProviderCaching(false).Options, false, false, false, unbacked: true);
        Assert.Throws<NotSupportedException>(() => context.Database.GenerateCreateScript());
        var model = context.GetService<IDesignTimeModel>().Model;
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        Assert.Throws<NotSupportedException>(() => context.GetService<IMigrationsSqlGenerator>().Generate(operations, model));
    }

    private static HierarchyContext<T> Create<T>(OceanBaseCompatibilityMode mode, bool expanded = false,
        bool assigned = false, bool composite = false) where T : struct
        => new(new DbContextOptionsBuilder<HierarchyContext<T>>()
            .UseOceanBase("Server=offline;Database=app", mode).EnableOceanBaseSchemaManagement("app")
            .EnableServiceProviderCaching(false).Options, expanded, assigned, composite);

    private sealed class HierarchyContext<T>(DbContextOptions<HierarchyContext<T>> options, bool expanded,
        bool assigned, bool composite, bool crossSchema = false, bool unbacked = false) : DbContext(options) where T : struct
    {
        protected override void OnModelCreating(ModelBuilder model)
        {
            model.HasDefaultSchema("app");
            var root = model.Entity<Root<T>>();
            root.UseTptMappingStrategy().ToTable("RootRows");
            root.Property(r => r.Name).HasMaxLength(40);
            if (assigned) root.Property(r => r.Id).ValueGeneratedNever();
            if (composite) root.HasKey(r => new { r.Id, r.TenantId });
            model.Entity<Middle<T>>().ToTable("MiddleRows");
            model.Entity<Leaf<T>>().ToTable("LeafRows");
            model.Entity<Leaf<T>>().HasIndex(l => l.Reading).HasDatabaseName("IX_Leaf_Reading");
            model.Entity<Sibling<T>>().ToTable("SiblingRows");
            if (expanded) model.Entity<Leaf<T>>().Property<int?>("Revision");
            if (unbacked) model.Entity<Leaf<T>>().Property<int?>("Unbacked").ValueGeneratedOnAdd();
            if (crossSchema)
            {
                root.ToTable("SameRows", "root");
                model.Entity<Middle<T>>().ToTable("SameRows", "child");
            }
        }
    }

    private abstract class Root<T> where T : struct
    {
        public T Id { get; set; }
        public int TenantId { get; set; }
        public string? Name { get; set; }
    }
    private class Middle<T> : Root<T> where T : struct { public int Number { get; set; } }
    private sealed class Leaf<T> : Middle<T> where T : struct { public int? Reading { get; set; } }
    private sealed class Sibling<T> : Root<T> where T : struct { public int Count { get; set; } }
}
