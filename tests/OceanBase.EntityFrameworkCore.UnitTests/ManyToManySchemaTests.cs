using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using OceanBase.EntityFrameworkCore.Metadata;
using Xunit;

namespace OceanBase.EntityFrameworkCore.UnitTests;

public sealed class ManyToManySchemaTests
{
    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Implicit_join_has_composite_foreign_keys_without_an_independent_identity(OceanBaseCompatibilityMode mode)
    {
        using var context = Create<ImplicitContext>(mode);
        var model = context.GetService<IDesignTimeModel>().Model;
        var join = model.FindEntityType("Membership")!;
        Assert.Equal(new[] { "CourseId", "StudentId" }, join.FindPrimaryKey()!.Properties.Select(p => p.Name));
        Assert.All(join.GetProperties(), p => Assert.Equal(ValueGenerated.Never, p.ValueGenerated));
        Assert.Equal(2, join.GetForeignKeys().Count());
        Assert.All(join.GetForeignKeys(), fk => Assert.Equal(DeleteBehavior.Cascade, fk.DeleteBehavior));
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        var table = Assert.Single(operations.OfType<CreateTableOperation>(), t => t.Name == "Memberships");
        Assert.Equal(new[] { "CourseRef", "StudentRef" }, table.PrimaryKey!.Columns);
        Assert.Equal(2, table.ForeignKeys.Count);
        foreach (var (principal, column) in new[] { ("Courses", "CourseRef"), ("Students", "StudentRef") })
        {
            var foreignKey = Assert.Single(table.ForeignKeys, fk => fk.PrincipalTable == principal);
            Assert.Equal(new[] { column }, foreignKey.Columns);
            Assert.Equal(new[] { "Id" }, foreignKey.PrincipalColumns);
            Assert.Equal(ReferentialAction.Cascade, foreignKey.OnDelete);
        }
        var index = Assert.Single(operations.OfType<CreateIndexOperation>(), i => i.Table == "Memberships");
        Assert.Equal(new[] { "StudentRef" }, index.Columns);
        Assert.False(index.IsUnique);
        Assert.All(table.Columns, c => Assert.NotEqual(true, c[OceanBaseRelationalAnnotationProvider.IdentityAnnotation]));
        foreach (var sql in new[] { context.Database.GenerateCreateScript(),
            string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(operations, model).Select(c => c.CommandText)) })
        {
            Assert.Equal(3, Regex.Matches(sql, "CREATE TABLE").Count);
            Assert.Equal(2, Regex.Matches(sql, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY").Count);
            Assert.Equal(2, Regex.Matches(sql, "FOREIGN KEY").Count);
            Assert.Contains("Memberships", sql);
            var unquoted = sql.Replace("`", "").Replace("\"", "");
            Assert.Contains("FOREIGN KEY (CourseRef) REFERENCES Courses (Id) ON DELETE CASCADE", unquoted);
            Assert.Contains("FOREIGN KEY (StudentRef) REFERENCES Students (Id) ON DELETE CASCADE", unquoted);
            Assert.Contains("ON Memberships (StudentRef)", unquoted);
        }
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Explicit_join_payload_evolves_without_recreating_principals(OceanBaseCompatibilityMode mode)
    {
        using var initial = Create<PayloadContext>(mode);
        using var evolved = Create<ExpandedPayloadContext>(mode);
        var before = initial.GetService<IDesignTimeModel>().Model;
        var after = evolved.GetService<IDesignTimeModel>().Model;
        var differ = initial.GetService<IMigrationsModelDiffer>();
        var creates = differ.GetDifferences(null, before.GetRelationalModel());
        var join = Assert.Single(creates.OfType<CreateTableOperation>(), t => t.Name == "CourseLinks");
        Assert.Equal(2, join.PrimaryKey!.Columns.Length);
        Assert.Equal(2, join.ForeignKeys.Count);
        Assert.All(join.Columns, c => Assert.NotEqual(true, c[OceanBaseRelationalAnnotationProvider.IdentityAnnotation]));
        var forward = differ.GetDifferences(before.GetRelationalModel(), after.GetRelationalModel());
        var add = Assert.IsType<AddColumnOperation>(Assert.Single(forward));
        Assert.Equal("CourseLinks", add.Table);
        Assert.Equal("Note", add.Name);
        Assert.Contains("ALTER TABLE", string.Concat(initial.GetService<IMigrationsSqlGenerator>()
            .Generate(forward, after).Select(c => c.CommandText)));
        var reverse = differ.GetDifferences(after.GetRelationalModel(), before.GetRelationalModel());
        Assert.Equal("Note", Assert.IsType<DropColumnOperation>(Assert.Single(reverse)).Name);
        var sql = string.Concat(initial.GetService<IMigrationsSqlGenerator>().Generate(creates, before).Select(c => c.CommandText));
        Assert.Equal(2, Regex.Matches(sql, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY").Count);
    }

    private static T Create<T>(OceanBaseCompatibilityMode mode) where T : DbContext
        => (T)Activator.CreateInstance(typeof(T), new DbContextOptionsBuilder()
            .UseOceanBase("Server=offline;Database=links", mode).Options)!;

    private sealed class Student { public int Id { get; set; } public string Name { get; set; } = ""; public List<Course> Courses { get; set; } = []; }
    private sealed class Course { public int Id { get; set; } public string Name { get; set; } = ""; public List<Student> Students { get; set; } = []; }
    private sealed class Link { public int StudentId { get; set; } public int CourseId { get; set; } public int? Version { get; set; } public string? Note { get; set; } }

    private sealed class ImplicitContext(DbContextOptions options) : DbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder model)
        {
            Principals(model);
            model.Entity<Student>().HasMany(s => s.Courses).WithMany(c => c.Students)
                .UsingEntity<Dictionary<string, object>>("Membership",
                    r => r.HasOne<Course>().WithMany().HasForeignKey("CourseId"),
                    l => l.HasOne<Student>().WithMany().HasForeignKey("StudentId"),
                    j => { j.ToTable("Memberships"); j.HasKey("CourseId", "StudentId");
                        j.IndexerProperty<int>("CourseId").HasColumnName("CourseRef");
                        j.IndexerProperty<int>("StudentId").HasColumnName("StudentRef"); });
        }
    }
    private class PayloadContext(DbContextOptions options) : DbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder model)
        {
            Principals(model);
            model.Entity<Student>().HasMany(s => s.Courses).WithMany(c => c.Students).UsingEntity<Link>(
                r => r.HasOne<Course>().WithMany().HasForeignKey(l => l.CourseId),
                l => l.HasOne<Student>().WithMany().HasForeignKey(l => l.StudentId),
                j => { j.ToTable("CourseLinks"); j.HasKey(l => new { l.CourseId, l.StudentId }); j.Property(l => l.Version).IsConcurrencyToken(); });
            model.Entity<Link>().Ignore(l => l.Note);
        }
    }
    private sealed class ExpandedPayloadContext(DbContextOptions options) : PayloadContext(options)
    {
        protected override void OnModelCreating(ModelBuilder model)
        { base.OnModelCreating(model); model.Entity<Link>().Property(l => l.Note).HasMaxLength(60); }
    }
    private static void Principals(ModelBuilder model)
    {
        model.Entity<Student>().ToTable("Students").Property(s => s.Name).HasMaxLength(40);
        model.Entity<Course>().ToTable("Courses").Property(c => c.Name).HasMaxLength(40);
    }
}
