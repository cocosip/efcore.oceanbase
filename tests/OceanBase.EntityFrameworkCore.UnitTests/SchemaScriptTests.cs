using System;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Xunit;

namespace OceanBase.EntityFrameworkCore.UnitTests
{
    public sealed class SchemaScriptTests
    {
        [Theory]
        [InlineData(OceanBaseCompatibilityMode.MySql)]
        [InlineData(OceanBaseCompatibilityMode.Oracle)]
        public void Create_script_is_offline_and_preserves_relational_graphs(OceanBaseCompatibilityMode mode)
        {
            using var context = Create(mode, "graph");
            var sql = context.Database.GenerateCreateScript();
            var q = mode == OceanBaseCompatibilityMode.MySql ? '`' : '"';
            string Q(string name) => q + name + q;
            Assert.Contains("CREATE TABLE " + Q("Parents"), sql);
            Assert.Contains("CONSTRAINT " + Q("PK_Parents") + " PRIMARY KEY (" + Q("TenantId") + ", " + Q("Id") + ")", sql);
            Assert.Contains("CONSTRAINT " + Q("AK_Parents_TenantId_Code") + " UNIQUE (" + Q("TenantId") + ", " + Q("Code") + ")", sql);
            Assert.Contains(Q("Name") + (mode == OceanBaseCompatibilityMode.MySql ? " LONGTEXT NOT NULL" : " NVARCHAR2(2000) NOT NULL"), sql);
            Assert.Contains(Q("Version") + (mode == OceanBaseCompatibilityMode.MySql ? " INT NULL" : " NUMBER(10) NULL"), sql);
            Assert.Contains("CREATE UNIQUE INDEX " + Q("IX_Parent_Code") + " ON " + Q("Parents") + " (" + Q("Code") + " DESC)", sql);
            Assert.Contains("CONSTRAINT " + Q("CK_Parent_Id") + " CHECK (" + Q("Id") + " > 0)", sql);
            Assert.Contains("ALTER TABLE " + Q("Children") + " ADD CONSTRAINT " + Q("FK_Child_Parent")
                + " FOREIGN KEY (" + Q("TenantId") + ", " + Q("ParentCode") + ") REFERENCES " + Q("Parents")
                + " (" + Q("TenantId") + ", " + Q("Code") + ") ON DELETE CASCADE", sql);
            Assert.True(sql.IndexOf("ALTER TABLE", StringComparison.Ordinal) > sql.LastIndexOf("CREATE TABLE", StringComparison.Ordinal));
            Assert.DoesNotContain("AUTO_INCREMENT", sql);
            Assert.DoesNotContain("IDENTITY", sql);
        }

        [Theory]
        [InlineData(OceanBaseCompatibilityMode.MySql)]
        [InlineData(OceanBaseCompatibilityMode.Oracle)]
        public void Create_script_supports_identity_defaults_and_computed_values(OceanBaseCompatibilityMode mode)
        {
            using var context = Create(mode, "generated");
            var sql = context.Database.GenerateCreateScript();
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "`Id` INT NOT NULL AUTO_INCREMENT" : "\"Id\" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL", sql);
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "`Caption` VARCHAR(40) DEFAULT ('can''t') NOT NULL"
                : "\"Caption\" NVARCHAR2(40) DEFAULT N'can''t' NOT NULL", sql);
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "DEFAULT (7)" : "DEFAULT 7", sql);
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "DEFAULT ('Ready')" : "DEFAULT N'Ready'", sql);
            Assert.Contains("DEFAULT (CURRENT_TIMESTAMP)", sql);
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql
                ? "`Twice` INT GENERATED ALWAYS AS (BASE_VALUE * 2) VIRTUAL"
                : "\"Twice\" GENERATED ALWAYS AS (BASE_VALUE * 2) VIRTUAL", sql);
        }

        [Theory]
        [InlineData(OceanBaseCompatibilityMode.MySql)]
        [InlineData(OceanBaseCompatibilityMode.Oracle)]
        public void Script_qualifies_and_escapes_names_and_omits_excluded_tables_and_views(OceanBaseCompatibilityMode mode)
        {
            using var context = Create(mode, "names");
            var sql = context.Database.GenerateCreateScript();
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "`s``\"`.`t``\"`" : "\"s`\"\"\".\"t`\"\"\"", sql);
            Assert.DoesNotContain("External", sql);
            Assert.DoesNotContain("ViewRows", sql);
        }

        [Theory]
        [InlineData("sequence")]
        [InlineData("trigger")]
        [InlineData("filter")]
        [InlineData("comment")]
        [InlineData("unknown-default")]
        [InlineData("unknown-computed")]
        [InlineData("multiple-identity")]
        [InlineData("nonkey-generated")]
        [InlineData("unsupported-identity")]
        [InlineData("model-collation")]
        [InlineData("tpc-identity")]
        public void Unsupported_schema_features_fail_explicitly_without_opening(string shape)
        {
            foreach (var mode in Enum.GetValues<OceanBaseCompatibilityMode>())
            {
                using var context = Create(mode, shape);
                Assert.Throws<NotSupportedException>(() => context.Database.GenerateCreateScript());
            }
        }

        [Theory]
        [InlineData("stored")]
        [InlineData("collation")]
        [InlineData("computed-collation")]
        public void Oracle_unsupported_store_options_are_not_silently_dropped(string shape)
        {
            using var context = Create(OceanBaseCompatibilityMode.Oracle, shape);
            Assert.Throws<NotSupportedException>(() => context.Database.GenerateCreateScript());
            using var mysql = Create(OceanBaseCompatibilityMode.MySql, shape);
            var sql = mysql.Database.GenerateCreateScript();
            Assert.Contains(shape == "stored" ? "STORED" : "COLLATE `utf8mb4_bin`", sql);
        }

        [Theory]
        [InlineData(OceanBaseCompatibilityMode.MySql)]
        [InlineData(OceanBaseCompatibilityMode.Oracle)]
        public void Owned_and_many_to_many_tables_and_cyclic_foreign_keys_are_emitted_after_all_tables(OceanBaseCompatibilityMode mode)
        {
            using var context = Create(mode, "relationships");
            var script = context.Database.GenerateCreateScript();
            var q = mode == OceanBaseCompatibilityMode.MySql ? '`' : '"';
            Assert.Contains("CREATE TABLE " + q + "OwnedLabels" + q, script);
            Assert.Contains("CREATE TABLE " + q + "PersonTag" + q, script);
            Assert.Contains(q + "City" + q, script);
            Assert.Contains("ON DELETE SET NULL", script);
            Assert.True(script.IndexOf("ALTER TABLE", StringComparison.Ordinal) > script.LastIndexOf("CREATE TABLE", StringComparison.Ordinal));
            Assert.Equal(5, System.Text.RegularExpressions.Regex.Matches(script, "CREATE TABLE").Count);
            Assert.Equal(6, System.Text.RegularExpressions.Regex.Matches(script, "FOREIGN KEY").Count);
        }

        [Theory]
        [InlineData(OceanBaseCompatibilityMode.MySql)]
        [InlineData(OceanBaseCompatibilityMode.Oracle)]
        public void Client_Guid_keys_and_large_default_literals_do_not_become_identities(OceanBaseCompatibilityMode mode)
        {
            using var context = Create(mode, "guid-default");
            var script = context.Database.GenerateCreateScript();
            Assert.DoesNotContain("IDENTITY", script);
            Assert.DoesNotContain("AUTO_INCREMENT", script);
            Assert.Contains(mode == OceanBaseCompatibilityMode.MySql ? "DEFAULT ('text')" : "DEFAULT N'text'", script);
        }

        private static SchemaContext Create(OceanBaseCompatibilityMode mode, string shape)
            => new(new DbContextOptionsBuilder<SchemaContext>()
                .UseOceanBase("Server=offline;Database=must_not_connect", mode)
                .ReplaceService<IModelCacheKeyFactory, ShapeCacheKey>()
                .AddInterceptors(new RejectConnection()).Options, shape, mode);

        public sealed class ShapeCacheKey(ModelCacheKeyFactoryDependencies dependencies) : ModelCacheKeyFactory(dependencies)
        {
            public override object Create(DbContext context, bool designTime)
                => (base.Create(context, designTime), ((SchemaContext)context).Shape);
        }

        private sealed class SchemaContext(DbContextOptions<SchemaContext> options, string shape, OceanBaseCompatibilityMode mode) : DbContext(options)
        {
            public string Shape => shape;
            protected override void OnModelCreating(ModelBuilder modelBuilder)
            {
                if (shape == "graph")
                {
                    var parent = modelBuilder.Entity<Parent>();
                    parent.ToTable("Parents", t => t.HasCheckConstraint("CK_Parent_Id", mode == OceanBaseCompatibilityMode.MySql ? "`Id` > 0" : "\"Id\" > 0"));
                    parent.HasKey(r => new { r.TenantId, r.Id });
                    parent.Property(r => r.Id).ValueGeneratedNever();
                    parent.HasAlternateKey(r => new { r.TenantId, r.Code });
                    parent.Property(r => r.Code).HasMaxLength(32);
                    parent.HasIndex(r => r.Code).IsUnique().IsDescending().HasDatabaseName("IX_Parent_Code");
                    var child = modelBuilder.Entity<Child>();
                    child.ToTable("Children");
                    child.Property(r => r.Id).ValueGeneratedNever();
                    child.Property(r => r.ParentCode).HasMaxLength(32);
                    child.HasOne<Parent>().WithMany().HasForeignKey(r => new { r.TenantId, r.ParentCode })
                        .HasPrincipalKey(r => new { r.TenantId, r.Code }).OnDelete(DeleteBehavior.Cascade)
                        .HasConstraintName("FK_Child_Parent");
                    return;
                }
                if (shape == "relationships")
                {
                    modelBuilder.Entity<Person>().OwnsOne(p => p.Address, a => a.Property(v => v.City).HasColumnName("City"));
                    modelBuilder.Entity<Person>().OwnsMany(p => p.Labels, a =>
                    {
                        a.ToTable("OwnedLabels");
                        a.Property(v => v.Id).ValueGeneratedNever();
                    });
                    modelBuilder.Entity<Person>().HasMany(p => p.Tags).WithMany(t => t.People).UsingEntity("PersonTag");
                    modelBuilder.Entity<Person>().HasOne(p => p.FavoriteTag).WithMany().HasForeignKey(p => p.FavoriteTagId)
                        .OnDelete(DeleteBehavior.SetNull);
                    modelBuilder.Entity<Tag>().HasOne(t => t.Owner).WithMany().HasForeignKey(t => t.OwnerId).OnDelete(DeleteBehavior.Restrict);
                    modelBuilder.Entity<Profile>().HasKey(p => p.PersonId);
                    modelBuilder.Entity<Profile>().Property(p => p.PersonId).ValueGeneratedNever();
                    modelBuilder.Entity<Person>().HasOne(p => p.Profile).WithOne().HasForeignKey<Profile>(p => p.PersonId);
                    return;
                }
                if (shape == "guid-default")
                {
                    modelBuilder.Entity<GuidRow>().Property(p => p.Id).HasConversion<string>().HasMaxLength(36);
                    modelBuilder.Entity<GuidRow>().Property(p => p.Text).HasDefaultValue("text");
                    return;
                }
                var row = modelBuilder.Entity<Generated>();
                row.ToTable("Generated");
                row.Property(r => r.Caption).HasMaxLength(40);
                row.Property(r => r.State).HasConversion<string>().HasMaxLength(20);
                row.Property(r => r.BaseValue).HasColumnName("BASE_VALUE");
                switch (shape)
                {
                    case "generated":
                        row.Property(r => r.Caption).HasDefaultValue("can't");
                        row.Property(r => r.BaseValue).HasDefaultValue(7);
                        row.Property(r => r.State).HasDefaultValue(State.Ready);
                        row.Property(r => r.CreatedAt).HasDefaultValueSql("CURRENT_TIMESTAMP");
                        row.Property(r => r.Twice).HasComputedColumnSql("BASE_VALUE * 2", stored: false);
                        break;
                    case "names":
                        row.ToTable("t`\"", "s`\"");
                        modelBuilder.Entity<Child>().ToTable("External", t => t.ExcludeFromMigrations());
                        modelBuilder.Entity<Parent>().HasNoKey().ToView("ViewRows");
                        break;
                    case "sequence": modelBuilder.HasSequence<int>("Extra"); break;
                    case "seed": row.HasData(new Generated { Id = 1, Caption = "seed" }); break;
                    case "trigger": row.ToTable(t => t.HasTrigger("Trigger")); break;
                    case "filter": row.HasIndex(r => r.BaseValue).HasFilter("BaseValue > 0"); break;
                    case "comment": row.Property(r => r.Caption).HasComment("must not disappear"); break;
                    case "unknown-default": row.Property(r => r.Caption).HasDefaultValue(); break;
                    case "unknown-computed": row.Property(r => r.Twice).HasComputedColumnSql(); break;
                    case "multiple-identity":
                        row.HasKey(r => new { r.Id, r.BaseValue });
                        row.Property(r => r.Id).ValueGeneratedOnAdd();
                        row.Property(r => r.BaseValue).ValueGeneratedOnAdd();
                        break;
                    case "nonkey-generated": row.Property(r => r.BaseValue).ValueGeneratedOnAdd(); break;
                    case "unsupported-identity":
                        modelBuilder.Ignore<Generated>();
                        modelBuilder.Entity<SmallIdentity>();
                        break;
                    case "stored": row.Property(r => r.Twice).HasComputedColumnSql("BASE_VALUE * 2", stored: true); break;
                    case "collation": row.Property(r => r.Caption).UseCollation("utf8mb4_bin"); break;
                    case "computed-collation": row.Property(r => r.Caption).UseCollation("utf8mb4_bin").HasComputedColumnSql("LOWER('X')"); break;
                    case "model-collation": modelBuilder.UseCollation("utf8mb4_bin"); break;
                    case "tpc-identity":
                        modelBuilder.Ignore<Generated>();
                        modelBuilder.Entity<BaseRow>().UseTpcMappingStrategy().ToTable("BaseRows");
                        modelBuilder.Entity<BaseRow>().Property(r => r.Id).ValueGeneratedOnAdd();
                        modelBuilder.Entity<DerivedRow>().ToTable("DerivedRows");
                        break;
                    default: throw new InvalidOperationException("Unknown schema fixture.");
                }
            }
        }

        private sealed class Parent
        {
            public int TenantId { get; set; }
            public int Id { get; set; }
            public string Code { get; set; } = "";
            public string Name { get; set; } = "";
            public int? Version { get; set; }
        }
        private sealed class Child
        {
            public int Id { get; set; }
            public int TenantId { get; set; }
            public string ParentCode { get; set; } = "";
        }
        private sealed class Generated
        {
            public int Id { get; set; }
            public string Caption { get; set; } = "";
            public int BaseValue { get; set; }
            public State State { get; set; }
            public int Twice { get; set; }
            public DateTime CreatedAt { get; set; }
        }
        private sealed class SmallIdentity { public short Id { get; set; } }
        private enum State { Initial, Ready }
        private sealed class Person
        {
            public int Id { get; set; }
            public int? FavoriteTagId { get; set; }
            public Tag? FavoriteTag { get; set; }
            public Address Address { get; set; } = new();
            public Profile? Profile { get; set; }
            public System.Collections.Generic.List<Label> Labels { get; set; } = [];
            public System.Collections.Generic.List<Tag> Tags { get; set; } = [];
        }
        private sealed class Tag
        {
            public int Id { get; set; }
            public int? OwnerId { get; set; }
            public Person? Owner { get; set; }
            public System.Collections.Generic.List<Person> People { get; set; } = [];
        }
        private sealed class Address { public string City { get; set; } = ""; }
        private sealed class Profile { public int PersonId { get; set; } public string Description { get; set; } = ""; }
        private sealed class Label { public int Id { get; set; } public string Value { get; set; } = ""; }
        private sealed class GuidRow { public Guid Id { get; set; } public string Text { get; set; } = ""; }
        private class BaseRow { public int Id { get; set; } public string Name { get; set; } = ""; }
        private sealed class DerivedRow : BaseRow { public int Extra { get; set; } }
        private sealed class RejectConnection : DbConnectionInterceptor
        {
            public override InterceptionResult ConnectionOpening(System.Data.Common.DbConnection connection, ConnectionEventData eventData, InterceptionResult result)
                => throw new InvalidOperationException("Schema scripts must not open a connection.");
        }
    }
}
