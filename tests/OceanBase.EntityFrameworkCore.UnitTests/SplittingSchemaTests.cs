using System;
using System.Linq;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using OceanBase.EntityFrameworkCore.Metadata;
using Xunit;
using Xunit.Abstractions;

namespace OceanBase.EntityFrameworkCore.UnitTests;

public sealed class SplittingSchemaTests(ITestOutputHelper output)
{
    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql, false)]
    [InlineData(OceanBaseCompatibilityMode.MySql, true)]
    [InlineData(OceanBaseCompatibilityMode.Oracle, false)]
    [InlineData(OceanBaseCompatibilityMode.Oracle, true)]
    public void Fragment_primary_keys_receive_the_primary_table_identity(OceanBaseCompatibilityMode mode, bool wide)
    {
        if (wide) Check<long>(mode);
        else Check<int>(mode);
    }

    private static void Check<T>(OceanBaseCompatibilityMode mode) where T : struct
    {
        using var context = Create<T>(mode);
        using var evolved = Create<T>(mode, expanded: true);
        var model = context.GetService<IDesignTimeModel>().Model;
        var next = evolved.GetService<IDesignTimeModel>().Model;
        var differ = context.GetService<IMigrationsModelDiffer>();
        var operations = differ.GetDifferences(null, model.GetRelationalModel());
        var creates = operations.OfType<CreateTableOperation>().ToArray();
        Assert.Equal(3, creates.Length);
        foreach (var table in creates)
        {
            var key = Assert.Single(table.PrimaryKey!.Columns);
            Assert.Equal(table.Name == "Rows", table.Columns.Single(c => c.Name == key)
                [OceanBaseRelationalAnnotationProvider.IdentityAnnotation] is true);
        }
        foreach (var sql in new[] { context.Database.GenerateCreateScript(),
            string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(operations, model).Select(c => c.CommandText)) })
        {
            Assert.Equal(3, Regex.Matches(sql, "CREATE TABLE").Count);
            Assert.Single(Regex.Matches(sql, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY"));
            Assert.Equal(2, Regex.Matches(sql, "FOREIGN KEY").Count);
            Assert.Contains("DetailId", sql);
            Assert.Contains("MetricId", sql);
            Assert.Contains("DEFAULT", sql);
            Assert.Contains("GENERATED ALWAYS AS", sql);
            Assert.Contains("IX_Detail_Text", sql);
        }
        var changes = differ.GetDifferences(model.GetRelationalModel(), next.GetRelationalModel());
        var add = Assert.Single(changes.OfType<AddColumnOperation>());
        Assert.Equal("Details", add.Table);
        Assert.Equal("Revision", add.Name);
        Assert.Contains("ADD", string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(changes, next).Select(c => c.CommandText)));
        var reverse = differ.GetDifferences(next.GetRelationalModel(), model.GetRelationalModel());
        Assert.Equal("Details", Assert.Single(reverse.OfType<DropColumnOperation>()).Table);
        Assert.Contains("DROP COLUMN", string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(reverse, model).Select(c => c.CommandText)));
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Assigned_composite_and_Guid_keys_keep_fragment_foreign_keys_without_identities(OceanBaseCompatibilityMode mode)
    {
        CheckAssigned<int>(mode, false);
        CheckAssigned<int>(mode, true);
        CheckAssigned<Guid>(mode, false);
    }

    private static void CheckAssigned<T>(OceanBaseCompatibilityMode mode, bool composite) where T : struct
    {
        using var context = Create<T>(mode, assigned: typeof(T) != typeof(Guid), composite: composite);
        var model = context.GetService<IDesignTimeModel>().Model;
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        foreach (var sql in new[] { context.Database.GenerateCreateScript(),
            string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(operations, model).Select(c => c.CommandText)) })
        {
            Assert.DoesNotContain("AUTO_INCREMENT", sql);
            Assert.DoesNotContain("AS IDENTITY", sql);
            Assert.Equal(2, Regex.Matches(sql, "FOREIGN KEY").Count);
        }
        Assert.All(model.GetRelationalModel().Tables, t => Assert.Equal(composite ? 2 : 1, t.PrimaryKey!.Columns.Count));
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Identically_named_tables_in_different_schemas_generate_only_the_primary_identity(OceanBaseCompatibilityMode mode)
    {
        using var context = Create<int>(mode, crossSchema: true);
        Assert.Single(Regex.Matches(context.Database.GenerateCreateScript(), "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY"));
        var tables = context.GetService<IDesignTimeModel>().Model.GetRelationalModel().Tables.Where(t => t.Name == "Rows").ToArray();
        Assert.Equal(2, tables.Length);
        Assert.True(OceanBaseRelationalAnnotationProvider.IsIdentity(tables.Single(t => t.Schema == "app").Columns.Single(c => c.Name == "Id")));
        Assert.False(OceanBaseRelationalAnnotationProvider.IsIdentity(tables.Single(t => t.Schema == "fragment").Columns.Single(c => c.Name == "DetailId")));
        var model = context.GetService<IDesignTimeModel>().Model;
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        Assert.Throws<NotSupportedException>(() => context.GetService<IMigrationsSqlGenerator>().Generate(operations, model));
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Unbacked_generation_on_a_fragment_still_rejects(OceanBaseCompatibilityMode mode)
    {
        using var context = Create<int>(mode, unbacked: true);
        Assert.Throws<NotSupportedException>(() => context.Database.GenerateCreateScript());
        var model = context.GetService<IDesignTimeModel>().Model;
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        Assert.Throws<NotSupportedException>(() => context.GetService<IMigrationsSqlGenerator>().Generate(operations, model));
    }

    [Theory]
    [InlineData(OceanBaseCompatibilityMode.MySql)]
    [InlineData(OceanBaseCompatibilityMode.Oracle)]
    public void Shared_rows_emit_one_table_one_identity_and_one_shared_concurrency_column(OceanBaseCompatibilityMode mode)
    {
        using var context = new SharedContext(new DbContextOptionsBuilder<SharedContext>()
            .UseOceanBase("Server=offline;Database=app", mode).EnableServiceProviderCaching(false).Options);
        var model = context.GetService<IDesignTimeModel>().Model;
        var table = Assert.Single(model.GetRelationalModel().Tables);
        Assert.Single(table.PrimaryKey!.Columns);
        Assert.Equal(2, table.FindColumn("Id")!.PropertyMappings.Count());
        Assert.Equal(2, table.FindColumn("Version")!.PropertyMappings.Count());
        Assert.Empty(table.ForeignKeyConstraints);
        foreach (var column in table.Columns)
            output.WriteLine(column.Name + ": " + string.Join(", ", column.PropertyMappings.Select(m => m.Property.DeclaringType.Name + "." + m.Property.Name + "=" + m.Property.ValueGenerated)));
        var operations = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel());
        Assert.Single(operations.OfType<CreateTableOperation>());
        foreach (var sql in new[] { context.Database.GenerateCreateScript(),
            string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(operations, model).Select(c => c.CommandText)) })
        {
            Assert.Single(Regex.Matches(sql, "CREATE TABLE"));
            Assert.Single(Regex.Matches(sql, "AUTO_INCREMENT|GENERATED BY DEFAULT AS IDENTITY"));
            Assert.Single(Regex.Matches(sql, "Version"));
            Assert.DoesNotContain("FOREIGN KEY", sql);
        }
    }

    private sealed class SharedContext(DbContextOptions<SharedContext> options) : DbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder model)
        {
            model.Entity<Principal>().ToTable("SharedRows");
            model.Entity<Dependent>().ToTable("SharedRows");
            model.Entity<Principal>().Property(p => p.Version).IsConcurrencyToken();
            model.Entity<Dependent>().Property(p => p.Version).IsConcurrencyToken();
            model.Entity<Dependent>().Property(p => p.Text).HasMaxLength(40);
            model.Entity<Principal>().HasOne(p => p.Detail).WithOne().HasForeignKey<Dependent>(d => d.Id);
        }
    }
    private sealed class Principal { public int Id { get; set; } public int? Version { get; set; } public Dependent? Detail { get; set; } }
    private sealed class Dependent { public int Id { get; set; } public int? Version { get; set; } public string? Text { get; set; } }

    private static SplitContext<T> Create<T>(OceanBaseCompatibilityMode mode, bool expanded = false, bool assigned = false,
        bool composite = false, bool crossSchema = false, bool unbacked = false) where T : struct
        => new(new DbContextOptionsBuilder<SplitContext<T>>().UseOceanBase("Server=offline;Database=app", mode)
            .EnableOceanBaseSchemaManagement("app").EnableServiceProviderCaching(false).Options,
            expanded, assigned, composite, crossSchema, unbacked);

    private sealed class SplitContext<T>(DbContextOptions<SplitContext<T>> options, bool expanded, bool assigned,
        bool composite, bool crossSchema, bool unbacked) : DbContext(options) where T : struct
    {
        protected override void OnModelCreating(ModelBuilder model)
        {
            model.HasDefaultSchema("app");
            var row = model.Entity<Row<T>>();
            row.ToTable("Rows");
            if (assigned) row.Property(r => r.Id).ValueGeneratedNever();
            if (composite) row.HasKey(r => new { r.Id, r.TenantId });
            row.Property(r => r.Text).HasMaxLength(40);
            row.Property(r => r.Counter).HasDefaultValue(5);
            row.Property(r => r.Computed).HasComputedColumnSql("1 + 1");
            if (unbacked) row.Property(r => r.Text).ValueGeneratedOnAdd();
            if (expanded) row.Property<int?>("Revision");
            row.HasIndex(r => r.Text).HasDatabaseName("IX_Detail_Text");
            row.SplitToTable(crossSchema ? "Rows" : "Details", crossSchema ? "fragment" : "app", table =>
            {
                table.Property(r => r.Id).HasColumnName("DetailId");
                table.Property(r => r.Text);
                if (expanded) table.Property("Revision");
            });
            row.SplitToTable("Metrics", "app", table =>
            {
                table.Property(r => r.Id).HasColumnName("MetricId");
                table.Property(r => r.Counter);
                table.Property(r => r.Computed);
            });
        }
    }
    private sealed class Row<T> where T : struct
    {
        public T Id { get; set; }
        public int TenantId { get; set; }
        public string? Name { get; set; }
        public string? Text { get; set; }
        public int Counter { get; set; }
        public int Computed { get; set; }
    }
}
